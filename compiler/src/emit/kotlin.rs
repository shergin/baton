//! The Kotlin emitter: fragments' lenses and `@inline` fragments' values,
//! operation values with their plans and root lenses, and the shared file of
//! interned types and slots, the conditions and argument sites, the
//! schema's enums and its input objects. A mutation's optimistic response
//! and action come next.
//!
//! Output per host file `X.kt` is `X.baton.kt`, in the host's package; the
//! code of a `.graphql` source and the shared `Baton.baton.kt` take the
//! package `baton.json` names under `kotlin`. One printer per output:
//! `shared` writes the shared file, `lens` the lenses and values,
//! `operation` the operation values and `plan` their plans; `literal`
//! holds what they share.

mod lens;
mod literal;
mod operation;
mod plan;
mod shared;

use std::collections::{BTreeMap, BTreeSet};

use super::Output;
use crate::config::Config;
use crate::decide::{NormalizationKind, NormalizationSelection, Program, ReaderPlan};
use crate::kotlin_names::{KotlinNaming, RUNTIME_NAMES, STABLE, enum_type_name, input_type_name};
use lens::Lenses;
use literal::Converters;
use shared::ConnectionTypes;

/// The format of generated Kotlin: what it names in the runtime. The
/// runtime declares a marker object per format it reads, `baton.Format<N>`,
/// and the shared file names the one of its format. Kotlin's numbers are
/// its own, as a format is per emitter.
pub const FORMAT: u32 = 1;

/// The first line of every generated file.
const GENERATED: &str = "// Generated by batonc. Do not edit.";

/// The Kotlin target: Kotlin's names, which the program is decided in, the
/// packages its files take, and the printers that write the decided
/// program.
pub struct Kotlin {
    naming: KotlinNaming,
    /// The Kotlin type of each mapped scalar's converter, by the converter.
    types: BTreeMap<String, String>,
    /// The package of the shared file and of the code of a source that
    /// declares none of its own.
    shared_package: Option<String>,
    /// The package each Kotlin host declares, by its path: none for a file
    /// in the default package. A source not here takes the shared package.
    packages: BTreeMap<String, Option<String>>,
}

impl Kotlin {
    /// The target `config` configures, with the package each Kotlin host of
    /// the run declares.
    pub fn new(config: &Config, packages: BTreeMap<String, Option<String>>) -> Kotlin {
        Kotlin {
            naming: KotlinNaming::new(config),
            types: config
                .kotlin_types()
                .into_values()
                .map(|converted| (converted.converter, converted.type_name))
                .collect(),
            shared_package: config.kotlin_package().map(str::to_string),
            packages,
        }
    }

    /// The names to decide a program in for this target.
    pub fn naming(&self) -> &KotlinNaming {
        &self.naming
    }

    /// The package the code generated for `source` takes.
    fn package_of(&self, source: &str) -> Option<&str> {
        match self.packages.get(source) {
            Some(package) => package.as_deref(),
            None => self.shared_package.as_deref(),
        }
    }

    /// The Kotlin of a program decided in this target's names.
    pub fn emit(&self, program: &Program) -> Output {
        let converters = Converters { types: &self.types };
        let lenses = Lenses {
            converters: &converters,
            fragments: program
                .fragments
                .iter()
                .map(|fragment| (fragment.name.as_str(), &fragment.lens))
                .collect(),
            shared: &program.shared,
        };
        let mut bodies: BTreeMap<String, Vec<String>> = BTreeMap::new();
        for fragment in &program.fragments {
            bodies
                .entry(fragment.source.clone())
                .or_default()
                .push(lenses.fragment_text(fragment));
        }
        for operation in &program.operations {
            bodies
                .entry(operation.source.clone())
                .or_default()
                .push(operation::operation_text(operation, &lenses));
        }
        let files = bodies
            .into_iter()
            .map(|(source, texts)| {
                let package = self.package_of(&source);
                let body = texts.join("\n");
                let shared_imports = self.shared_imports(program, &body, package);
                let text = if body.is_empty() {
                    format!("{GENERATED}\n{}", package_line(package))
                } else {
                    format!("{}{body}", header(package, &body, &shared_imports))
                };
                (source, text)
            })
            .collect();
        Output {
            shared: shared::shared_text(
                &program.shared,
                &connections(program),
                &converters,
                self.shared_package.as_deref(),
            ),
            files,
        }
    }

    /// What `body`, the code of a file in `package`, names from the shared
    /// file in another package: its objects, enums and input objects.
    fn shared_imports(&self, program: &Program, body: &str, package: Option<&str>) -> Vec<String> {
        let Some(shared) = self.shared_package.as_deref() else {
            return Vec::new();
        };
        if package == Some(shared) {
            return Vec::new();
        }
        let spelled = identifiers(body);
        let mut declared: BTreeSet<String> = ["Types", "Slots", "AbstractSlots", "Guards", "Sites"]
            .into_iter()
            .map(str::to_string)
            .collect();
        declared.extend(program.shared.enums.keys().map(|name| enum_type_name(name)));
        declared.extend(
            program
                .shared
                .inputs
                .keys()
                .map(|name| input_type_name(name)),
        );
        declared
            .into_iter()
            .filter(|name| spelled.contains(name.as_str()))
            .map(|name| format!("{shared}.{name}"))
            .collect()
    }
}

/// The `package` line, or nothing for the default package.
fn package_line(package: Option<&str>) -> String {
    match package {
        Some(package) => format!("\npackage {package}\n"),
        None => String::new(),
    }
}

/// The lines before a file's declarations: the marker, the opt-in into the
/// runtime's contract with generated code, the package, and an import of
/// each runtime name `body` spells and of each of `extra`.
pub(super) fn header(package: Option<&str>, body: &str, extra: &[String]) -> String {
    let spelled = identifiers(body);
    let mut imports: Vec<String> = RUNTIME_NAMES
        .iter()
        .filter(|name| spelled.contains(**name))
        .map(|name| format!("baton.{name}"))
        .collect();
    // A lens is stable to Compose: equal by its anchor, and every read
    // registers what it reads.
    if body.contains("@Stable\n") {
        imports.push(STABLE.to_string());
    }
    imports.extend(extra.iter().cloned());
    imports.sort();
    imports.dedup();
    let mut text = format!("{GENERATED}\n@file:OptIn(baton.Generated::class)\n");
    text.push_str(&package_line(package));
    if !imports.is_empty() {
        text.push('\n');
        for import in imports {
            text.push_str(&format!("import {import}\n"));
        }
    }
    text.push('\n');
    text
}

/// The identifiers `body` spells unqualified, outside its string literals:
/// not after a dot.
fn identifiers(body: &str) -> BTreeSet<&str> {
    let mut names = BTreeSet::new();
    let bytes = body.as_bytes();
    let mut index = 0;
    while index < bytes.len() {
        let byte = bytes[index];
        if byte == b'"' {
            index += 1;
            while index < bytes.len() && bytes[index] != b'"' {
                if bytes[index] == b'\\' {
                    index += 1;
                }
                index += 1;
            }
            index += 1;
            continue;
        }
        if byte.is_ascii_alphabetic() || byte == b'_' {
            let begin = index;
            while index < bytes.len()
                && (bytes[index].is_ascii_alphanumeric() || bytes[index] == b'_')
            {
                index += 1;
            }
            if begin == 0 || bytes[begin - 1] != b'.' {
                names.insert(&body[begin..index]);
            }
            continue;
        }
        index += 1;
    }
    names
}

/// Each connection type the plans paginate or a lens reads the state of,
/// with its edge and page info types.
fn connections(program: &Program) -> BTreeMap<String, ConnectionTypes> {
    let mut connections = BTreeMap::new();
    for operation in &program.operations {
        collect_connections(&operation.normalization, &mut connections);
        lens_connections(&operation.data, &mut connections);
    }
    for fragment in &program.fragments {
        lens_connections(&fragment.lens, &mut connections);
    }
    connections
}

fn lens_connections(lens: &ReaderPlan, into: &mut BTreeMap<String, ConnectionTypes>) {
    if let Some(connection) = &lens.connection {
        into.entry(connection.connection_type.clone())
            .or_insert_with(|| ConnectionTypes {
                edge: connection.edge_type.clone(),
                page_info: connection.page_info_type.clone(),
            });
    }
    for child in &lens.nested {
        lens_connections(child, into);
    }
}

fn collect_connections(
    selection: &NormalizationSelection,
    into: &mut BTreeMap<String, ConnectionTypes>,
) {
    for variant in &selection.variants {
        for field in &variant.fields {
            let NormalizationKind::Linked {
                connection,
                selection: child,
                ..
            } = &field.kind
            else {
                continue;
            };
            if let Some(connection) = connection {
                into.entry(child.type_name.clone())
                    .or_insert_with(|| ConnectionTypes {
                        edge: connection.edge_type.clone(),
                        page_info: connection.page_info_type.clone(),
                    });
            }
            collect_connections(child, into);
        }
    }
}

/// The Kotlin of `plan` as the driver writes it for the target `config`
/// configures, its sources in the shared package, or the names some scope
/// would declare twice.
#[cfg(test)]
pub fn kotlin(
    plan: &crate::pipeline::Plan,
    config: &Config,
) -> Result<Output, Vec<crate::naming::NameError>> {
    let target = Kotlin::new(config, BTreeMap::new());
    let program = crate::decide::program(plan, target.naming())?;
    Ok(target.emit(&program))
}

