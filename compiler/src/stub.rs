//! The S0 emitter: enough Swift per document for the toolchain spike to
//! compile and for the property-type check to produce a diagnostic. The real
//! emitter replaces this once the plan IR is settled.

use std::fmt::Write as _;

use crate::documents::Document;
use crate::pipeline::{Plan, VariablePlan};
use crate::swift::Marker;

/// Renders the stub Swift for every document of one host file.
pub fn render(documents: &[&Document], plan: &Plan) -> String {
    let mut output = String::new();
    let _ = writeln!(output, "// Generated by batonc (S0 spike). Do not edit.");
    let _ = writeln!(output, "import Baton\n");
    for document in documents {
        let Some(embedded) = &document.embedded else {
            continue;
        };
        match embedded.marker {
            Marker::Fragment => {
                for fragment in plan
                    .fragments
                    .iter()
                    .filter(|fragment| document.text.contains(&fragment.name))
                {
                    let _ = writeln!(
                        output,
                        "/// Lens for `fragment {} on {}`.\npublic struct {}: Sendable {{\n    public init() {{}}\n}}\n",
                        fragment.name, fragment.type_condition, fragment.name
                    );
                }
            }
            Marker::Query | Marker::Mutation | Marker::Subscription => {
                for operation in plan
                    .operations
                    .iter()
                    .filter(|operation| document.text.contains(&operation.name))
                {
                    let _ = writeln!(
                        output,
                        "/// Operation value for `{} {}`.",
                        operation.kind, operation.name
                    );
                    let _ = writeln!(
                        output,
                        "public struct {}: Baton.Operation {{",
                        operation.name
                    );
                    for variable in &operation.variables {
                        let _ = writeln!(
                            output,
                            "    public var {}: {}",
                            variable.name,
                            swift_type(variable)
                        );
                    }
                    let _ = writeln!(output, "    public var resolution: Baton.Resolution? = nil");
                    let parameters: Vec<String> = operation
                        .variables
                        .iter()
                        .map(|variable| {
                            let default = if variable.type_name.ends_with('!') {
                                ""
                            } else {
                                " = nil"
                            };
                            format!("{}: {}{}", variable.name, swift_type(variable), default)
                        })
                        .collect();
                    let _ = writeln!(output, "    public init({}) {{", parameters.join(", "));
                    for variable in &operation.variables {
                        let _ = writeln!(output, "        self.{0} = {0}", variable.name);
                    }
                    let _ = writeln!(output, "    }}");
                    let _ = writeln!(
                        output,
                        "    public static let persistedID = \"{}\"",
                        operation.id
                    );
                    let _ = writeln!(
                        output,
                        "    public static func == (lhs: Self, rhs: Self) -> Bool {{"
                    );
                    if operation.variables.is_empty() {
                        let _ = writeln!(output, "        true");
                    } else {
                        let comparisons: Vec<String> = operation
                            .variables
                            .iter()
                            .map(|variable| format!("lhs.{0} == rhs.{0}", variable.name))
                            .collect();
                        let _ = writeln!(output, "        {}", comparisons.join(" && "));
                    }
                    let _ = writeln!(output, "    }}");
                    let _ = writeln!(output, "    public func hash(into hasher: inout Hasher) {{");
                    for variable in &operation.variables {
                        let _ = writeln!(output, "        hasher.combine({})", variable.name);
                    }
                    let _ = writeln!(output, "    }}\n}}\n");
                }
            }
        }
    }
    output
}

/// Maps a GraphQL variable type to the Swift type the stub uses.
fn swift_type(variable: &VariablePlan) -> String {
    let non_null = variable.type_name.ends_with('!');
    let base = variable.type_name.trim_end_matches('!');
    let swift = if let Some(inner) = base
        .strip_prefix('[')
        .and_then(|rest| rest.strip_suffix(']'))
    {
        format!(
            "[{}]",
            swift_type(&VariablePlan {
                name: String::new(),
                type_name: inner.to_string(),
            })
        )
    } else {
        match base {
            "ID" | "String" => "String",
            "Int" => "Int",
            "Float" => "Double",
            "Boolean" => "Bool",
            other => other,
        }
        .to_string()
    };
    if non_null { swift } else { format!("{swift}?") }
}
