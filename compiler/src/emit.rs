mod shared;
mod swift;
mod value;
mod writer;

use std::collections::BTreeMap;

use crate::config::Config;
use crate::decide;
use crate::names::NameError;
use crate::pipeline::Plan;

/// Generated Swift, grouped by the source file that declared the documents.
pub struct Output {
    pub files: BTreeMap<String, String>,
    pub shared: String,
}

/// The runtime's interface for generated code is SPI, so the generated file
/// imports it and an app's own files, which import `Baton`, do not see it.
const HEADER: &str =
    "// Generated by batonc. Do not edit.\nimport Foundation\n@_spi(Generated) import Baton\n";

/// The format of the generated code: what it names in the runtime, from the
/// plan tables to the lens requirements. The runtime declares a marker type
/// per format it reads, `Baton.Format<N>`, and the shared file names the one
/// of its format, so code of another format fails to compile at that line
/// and the marker says which side is behind. A change to what generated
/// code names in the runtime raises it, here and in the runtime together.
pub const FORMAT: u32 = 17;

/// The Swift of a plan, or the names it would have declared twice. A mapped
/// scalar reads as the Swift type `config` names for it.
pub fn emit(plan: &Plan, config: &Config) -> Result<Output, Vec<NameError>> {
    let program = decide::program(plan, &config.swift_types())?;
    let mut files: BTreeMap<String, String> = BTreeMap::new();
    for fragment in &program.fragments {
        let text = if fragment.inline {
            value::fragment_text(fragment)
        } else {
            lens::fragment_text(fragment)
        };
        files
            .entry(fragment.source.clone())
            .or_default()
            .push_str(&text);
    }
    for operation in &program.operations {
        files
            .entry(operation.source.clone())
            .or_default()
            .push_str(&operation::operation_text(operation, &program.shared));
    }
    for text in files.values_mut() {
        *text = format!("{HEADER}\n{text}");
    }
    Ok(Output {
        shared: shared::shared_text(&program.shared),
        files,
    })
}

